const N = 0.7; // normal
const G = 0.55; // 303 gate length (steps) for unslid notes
const sev = [0, 2, 4, 6];

/**
 * Shorthand for an acid step: time, step, accent?, slide?, octave, chromatic.
 * A slide holds the note `len` steps (default 1.6: past a 16th-note neighbour).
 */
const ac = (t: number, s: number, acc = false, slide = false, o = 0, c = 0, len = 1.6): NoteEvent =>
  n(t, s, slide ? len : G, acc ? A : N, o || undefined, c || undefined);
/** Eighth-note acid: slides must hold past a two-step gap. */
const ac8 = (t: number, s: number, acc = false, slide = false, o = 0, c = 0): NoteEvent => ac(t, s, acc, slide, o, c, 2.6);

